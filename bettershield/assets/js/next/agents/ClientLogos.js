const token = ( name ) => `var(--bs-ds-logo-${ name })`;

/**
 * One assistant's logo, or nothing for a name there's no logo for.
 * Decorative: the tool's name always sits beside it.
 *
 * @param {Object} props
 * @param {string} props.name A key of CLIENT_LOGOS.
 * @param {number} props.size Width and height, in pixels.
 */
export default function ClientLogo( { name, size = 20 } ) {
	// Two copies can be on a screen, and a gradient is found by its ID.
	const [ id ] = useState( () => `bs-ds-logo-${ ++made }` );
	const logo = CLIENT_LOGOS[ name ];

	if ( ! logo ) {
		return null;
	}

	return (
		<svg width={ size } height={ size } viewBox={ `0 0 ${ logo.box } ${ logo.box }` } aria-hidden="true" focusable="false">
			{ logo.gradient ? (
				<defs>
					<linearGradient id={ id } gradientUnits="userSpaceOnUse" x1="12" x2="12" y1="3" y2="21">
						{ logo.gradient.map( ( stop, index ) => (
							<stop key={ stop } offset={ index / ( logo.gradient.length - 1 ) } style={ { stopColor: token( stop ) } } />
						) ) }
					</linearGradient>
				</defs>
			) : null }
			{ logo.paths.map( ( { d, color, fillRule } ) => (
				<path key={ d } d={ d } fillRule={ fillRule } clipRule={ fillRule } style={ { fill: logo.gradient ? `url(#${ id })` : token( color ) } } />
			) ) }
		</svg>
	);
}
