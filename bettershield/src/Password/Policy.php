	/**
	 * The calm nudge, shown to the affected user on their own profile screen
	 * and nowhere else. Nothing is blocked and nothing expires; the copy says
	 * so, because the fear-free framing is the product.
	 */
	public function maybe_prompt(): void {
		$screen = function_exists( 'get_current_screen' ) ? get_current_screen() : null;

		if ( null === $screen || 'profile' !== $screen->id ) {
			return;
		}

		if ( '1' !== get_user_meta( get_current_user_id(), self::flag_key(), true ) ) {
			return;
		}

		// The length it asks for, and a link to the field: "below" was about
		// 1,500 px down and named no number (#2574).
		printf(
			'<div class="notice bs-notice notice-info"><p>%s <a href="#password">%s</a></p></div>',
			esc_html( $this->shortfall_sentence() ),
			esc_html__( 'Change it under Account Management.', 'bettershield' )
		);
	}

	/**
	 * What the nudge says first: the length this account is now asked for,
	 * and that the old password still works.
	 *
	 * The flag is set by any refusal, not only a short one: a long password
	 * built on a common word, the username or a run of keys is flagged too,
	 * and "shorter than" told that owner something untrue. So the sentence
	 * names the standard, not which part of it was missed.
	 */
	private function shortfall_sentence(): string {
		$user = wp_get_current_user();

		return sprintf(
			/* translators: %d: the minimum number of characters this account's password now needs. */
			__( 'Your password doesn’t meet this site’s new standard: at least %d characters and nothing easy to guess. It still works.', 'bettershield' ),
			$this->required_length( (array) $user->roles, $user )
		);
	}

	/**
	 * The same nudge on a store's My Account, above whichever of its pages
	 * is open. A store sends its customers away from the profile screen, so a
	 * flagged customer was never told, and the finding could not clear.
	 */
	public function maybe_prompt_on_store(): void {
		if ( ! is_user_logged_in() || '1' !== get_user_meta( get_current_user_id(), self::flag_key(), true ) ) {
			return;
		}

		$details = function_exists( 'wc_get_account_endpoint_url' ) ? (string) wc_get_account_endpoint_url( 'edit-account' ) : '';

		printf(
			'<div class="woocommerce-info" role="status">%s%s</div>',
			esc_html( $this->shortfall_sentence() . ' ' . __( 'Change it under Account details.', 'bettershield' ) ),
			'' !== $details ? ' <a href="' . esc_url( $details ) . '">' . esc_html__( 'Change your password', 'bettershield' ) . '</a>' : ''
		);
	}
}
