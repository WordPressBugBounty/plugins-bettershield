	/**
	 * A reset form submission, which is also how core registration sets the
	 * first password.
	 */
	public function check_reset( \WP_Error $errors, $user ): void {
		if ( ! $this->enforcing() || ! $user instanceof \WP_User ) {
			return;
		}

		// Core reads the proposed password from the same place; absent means
		// the form is being rendered, not submitted. A store's reset form
		// fires this same action, having verified the same reset key, and
		// posts the new password under its own field name — so both names are
		// read, and the first one present is the password being chosen.
		// phpcs:ignore WordPress.Security.NonceVerification.Missing -- the reset flow, core's or a store's, verifies its own key before this hook fires.
		$posted = isset( $_POST['pass1'] ) ? $_POST['pass1'] : ( $_POST['password_1'] ?? '' ); // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash, WordPress.Security.NonceVerification.Missing -- unslashed on the next line; a password is compared, never stored or output.

		$password = (string) wp_unslash( $posted );

		if ( '' === $password ) {
			return;
		}

		$refusal = $this->evaluate( $password, (array) $user->roles, array( $user->user_login, (string) $user->user_email, (string) $user->display_name ), $user );

		if ( null !== $refusal ) {
			$errors->add( $refusal->get_error_code(), $refusal->get_error_message() );
		}
	}

	/**
	 * A profile update carrying a new password — including an administrator
	 * creating an account through the new-user form.
	 *
	 * @param bool $update Whether this is an update rather than a creation.
	 * @param \stdClass $user The user data about to be saved.
	 */
	public function check_profile( \WP_Error $errors, bool $update, $user ): void {
		if ( ! $this->enforcing() || ! isset( $user->user_pass ) || '' === (string) $user->user_pass ) {
			return;
		}

		// The role the account will hold: the form's choice, or the stored
		// one on a self-service password change.
		$roles    = array();
		$existing = $update && isset( $user->ID ) ? get_userdata( (int) $user->ID ) : null;

		if ( isset( $user->role ) && '' !== (string) $user->role ) {
			$roles = array( (string) $user->role );
		} elseif ( $existing instanceof \WP_User ) {
			$roles = (array) $existing->roles;
		}

		$refusal = $this->evaluate(
			(string) $user->user_pass,
			$roles,
			array( (string) ( $user->user_login ?? '' ), (string) ( $user->user_email ?? '' ), (string) ( $user->display_name ?? '' ) ),
			$existing instanceof \WP_User ? $existing : null
		);

		if ( null !== $refusal ) {
			$errors->add( $refusal->get_error_code(), $refusal->get_error_message() );
		}
	}

	/**
	 * A password arriving through a store's own account page.
	 *
	 * The same evaluation the profile screen gets, from the same shape of
	 * object: a partial record carrying the ID and, when a password is being
	 * changed, the one that is about to be stored.
	 *
	 * @param \stdClass|mixed $user The user data about to be saved.
	 */
	public function check_store_account( \WP_Error $errors, $user ): void {
		$this->check_profile( $errors, true, $user );
	}

	/**
	 * A password chosen on a store's sign-up form.
	 *
	 * The filter carries the fields as they were typed rather than a user
	 * object, and it is applied before the account exists — so there is no
	 * stored role to read and the new account's own words are the ones it may
	 * not contain. A store that generates passwords never reaches this with
	 * one to check.
	 *
	 * @param mixed  $errors   WP_Error from WooCommerce, or whatever an earlier filter returned.
	 * @param string $username The username being registered.
	 * @param string $password The password as typed, empty when the store generates one.
	 * @param string $email    The email address being registered.
	 * @return mixed
	 */
	public function check_store_registration( $errors, $username = '', $password = '', $email = '' ) {
		if ( ! $this->enforcing() || ! is_wp_error( $errors ) || '' === (string) $password ) {
			return $errors;
		}

		$refusal = $this->evaluate(
			(string) $password,
			array( get_option( 'default_role', 'subscriber' ) ),
			array( (string) $username, (string) $email ),
			null
		);

		if ( null !== $refusal ) {
			$errors->add( $refusal->get_error_code(), $refusal->get_error_message() );
		}

		return $errors;
	}

	/**
	 * A password arriving through core's REST users route, on creation or on
	 * update.
	 *
	 * Runs after the route's permission callback and in place of its own
	 * callback, which is where core lets a refusal actually stop the write:
	 * returning a WP_Error here short-circuits the request with that error,
	 * and the caller sees the same wording the forms give. Returning null
	 * hands the request on to the callback untouched.
	 *
	 * @param mixed            $dispatch_result Whatever an earlier filter decided, or null.
	 * @param \WP_REST_Request $request         The request.
	 * @param string           $route           The matched route.
	 * @param array            $handler         The matched route handler.
	 * @return mixed
	 */
	public function check_rest( $dispatch_result, $request, $route = '', $handler = array() ) {
		// Somebody ahead of us has already replaced the dispatch; that
		// decision is theirs, not this policy's.
		if ( null !== $dispatch_result || ! $request instanceof \WP_REST_Request ) {
			return $dispatch_result;
		}

		/*
		 * Cheapest checks first, and deliberately so: this runs on every REST
		 * request the site serves, ours and everyone else's. Reading the policy
		 * option before knowing the request is even about a user was a query on
		 * every REST call to answer a question almost none of them ask.
		 */
		if ( ! in_array( $request->get_method(), array( 'POST', 'PUT', 'PATCH' ), true ) ) {
			return $dispatch_result;
		}

		/*
		 * `/wp/v2/users`, `/wp/v2/users/<id>` and `/wp/v2/users/me`, and the
		 * store's own twin of them, including its batch form.
		 *
		 * WooCommerce's customers route sets a password through
		 * `wc_create_new_customer()`, which fires
		 * `woocommerce_registration_errors` — a filter carrying the username
		 * and the email and never the password. So none of the three form
		 * hooks can read it there, and the account was created or updated with
		 * no policy applied at all, while the same weak password was refused
		 * on My Account, on the account-details form, on the reset form and on
		 * core's own users route. WC REST dispatches through this same filter,
		 * so the mechanism already here is what reaches it. Its batch route
		 * creates each item without dispatching again, so every item's
		 * password is judged here, before any of them is written.
		 *
		 * Namespaced copies of the users route registered by other plugins are
		 * not covered and are not this policy's business.
		 */
		$route = (string) $request->get_route();

		if ( ! RestAccounts::covers( $route ) ) {
			return $dispatch_result;
		}

		if ( ! $this->enforcing() ) {
			return $dispatch_result;
		}

		$store_route = RestAccounts::is_store_route( $route );

		foreach ( RestAccounts::passwords( $request ) as $entry ) {
			$refusal = $this->rest_refusal( $entry, $store_route );

			if ( null === $refusal ) {
				continue;
			}

			$data = array( 'status' => 400 );

			// In a batch, which item was refused; the whole batch is, so that
			// no account in it is created with a password under the bar.
			if ( '' !== $entry['item'] ) {
				$data['item'] = $entry['item'];
			}

			return new \WP_Error( $refusal->get_error_code(), $refusal->get_error_message(), $data );
		}

		return $dispatch_result;
	}

	/**
	 * The policy's answer for one password a REST request sets.
	 *
	 * @param array{password: string, fields: array<string, mixed>, account: int, item: string} $entry From RestAccounts::passwords().
	 */
	private function rest_refusal( array $entry, bool $store_route ): ?\WP_Error {
		$fields   = $entry['fields'];
		$existing = $entry['account'] > 0 ? get_userdata( $entry['account'] ) : false;

		// The role the account will hold once this request is done: what the
		// request asks for, or what the account already has. An update that
		// does not mention roles keeps its own, and a creation that names none
		// gets the site's default — each of which can carry a different bar.
		$roles = array_map( array( RestAccounts::class, 'text' ), (array) ( $fields['roles'] ?? array() ) );

		if ( array() === $roles ) {
			if ( $existing instanceof \WP_User ) {
				$roles = (array) $existing->roles;
			} elseif ( $store_route ) {
				// The store's route mints one role and names it nowhere: a
				// customer. It cannot create an administrator, which is why
				// this is a bar bypass for the bulk of a shop's accounts
				// rather than a way up.
				$roles = array( 'customer' );
			} else {
				$roles = array( (string) get_option( 'default_role', 'subscriber' ) );
			}
		}

		return $this->evaluate(
			$entry['password'],
			$roles,
			array(
				isset( $fields['username'] ) ? RestAccounts::text( $fields['username'] ) : ( $existing instanceof \WP_User ? $existing->user_login : '' ),
				isset( $fields['email'] ) ? RestAccounts::text( $fields['email'] ) : ( $existing instanceof \WP_User ? $existing->user_email : '' ),
				isset( $fields['name'] ) ? RestAccounts::text( $fields['name'] ) : ( $existing instanceof \WP_User ? $existing->display_name : '' ),
			),
			$existing instanceof \WP_User ? $existing : null
		);
	}

	/* ---- observation ------------------------------------------------------ */

	/**
	 * After core has authenticated a sign-in, note whether the password that
	 * just proved correct meets the policy. Runs at priority 30, after core's
	 * checks: only a password that actually signed someone in is evaluated,
	 * so a wrong guess can never flag an account.
	 *
	 * Never blocks, never delays, stores only a yes/no flag.
	 *
	 * @param \WP_User|\WP_Error|null $user
	 * @return \WP_User|\WP_Error|null
	 */
	public function observe_login( $user, string $username, string $password ) {
		if ( ! $user instanceof \WP_User || '' === $password || ! $this->settings()['enabled'] ) {
			return $user;
		}

		$refusal = $this->evaluate( $password, (array) $user->roles, array( $user->user_login, (string) $user->user_email, (string) $user->display_name ), $user );

		if ( null !== $refusal ) {
			update_user_meta( $user->ID, self::flag_key(), '1' );
		} elseif ( '' !== (string) get_user_meta( $user->ID, self::flag_key(), true ) ) {
			/*
			 * Asked of the meta cache the sign-in has already filled, because
			 * the delete cannot be: core looks the key up before it can learn
			 * there is nothing to remove, uncached, and the overwhelmingly
			 * common sign-in is a strong password on an account that carries
			 * no flag at all.
			 */
			delete_user_meta( $user->ID, self::flag_key() );
		}

		return $user;
	}

	/**
	 * A password reset is a new password on every site, as a change from the
	 * profile is: core fires this for "Lost your password?" and never
	 * `profile_update`, so clearing this site's flag alone left every other
	 * site counting the account and asking it to change its password again.
	 */
	public function clear_flag( \WP_User $user ): void {
		self::forget_everywhere( $user->ID );
	}

	/**
	 * The flag's key on this site.
	 *
	 * The policy is each site's own setting, and user meta is one table for a
	 * whole network: kept under one key, a sign-in on a site with a strict
	 * policy flagged the account on a lenient one, and a sign-in on the
	 * lenient one cleared the strict site's finding while the password was
	 * still below it. So a network keeps it per site, as the two-factor clock
	 * and the parked sign-in are kept.
	 */
	public static function flag_key(): string {
		return is_multisite() ? self::WEAK_META . '_' . get_current_blog_id() : self::WEAK_META;
	}

	/** This site's flag on an account, gone. */
	public static function forget( int $user_id ): void {
		delete_user_meta( $user_id, self::flag_key() );
	}

	/**
	 * Every site's flag on an account, gone: a new password is new on all of
	 * them, and an account deleted or erased leaves nothing anywhere. The key
	 * a network wrote before it was kept per site goes too.
	 */
	public static function forget_everywhere( int $user_id ): void {
		global $wpdb;

		delete_user_meta( $user_id, self::WEAK_META );

		if ( ! is_multisite() ) {
			return;
		}

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- one account's keys by prefix, which no core API lists; each is then deleted through the API, which clears its cache.
		$keys = (array) $wpdb->get_col(
			$wpdb->prepare(
				'SELECT meta_key FROM %i WHERE user_id = %d AND meta_key LIKE %s',
				$wpdb->usermeta,
				$user_id,
				$wpdb->esc_like( self::WEAK_META . '_' ) . '%'
			)
		);

		foreach ( $keys as $key ) {
			delete_user_meta( $user_id, (string) $key );
		}
	}

	/**
	 * @param int $user_id
	 * @param \WP_User $old_user The user before the update.
	 */
	public function clear_flag_on_password_change( int $user_id, $old_user ): void {
		$now = get_userdata( $user_id );

		if ( $now instanceof \WP_User && $old_user instanceof \WP_User && $now->user_pass !== $old_user->user_pass ) {
			self::forget_everywhere( $user_id );
		}
	}

	/**
	 * Accounts currently flagged: the count for the finding, and whether any
	 * of them is privileged for the severity.
	 *
	 * Read once per request. The audit asks twice — for the evidence and
	 * for the severity — and on a site with thousands of members the answer
	 * was the user table in memory, twice. So: ids rather than accounts, a
	 * bounded page of them, and the total counted by the database. Only the
	 * accounts read are hydrated, for the privileged count, and `complete`
	 * says whether that was every one of them.
	 *
	 * @return array{total: int, privileged: int, complete: bool}
	 */
	public function flagged(): array {
		$site = (int) get_current_blog_id();

		if ( isset( self::$flagged[ $site ] ) ) {
			return self::$flagged[ $site ];
		}

		$query = new \WP_User_Query(
			array(
				'meta_key'    => self::flag_key(), // phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_key -- read by the daily audit, never on a front-end request.
				'meta_value'  => '1', // phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_value
				// An account waiting for a new password cannot sign in with
				// the weak one, so it no longer counts against the site.
				'exclude'     => \BetterShield\Remediation\PasswordHold::blocked_ids(), // phpcs:ignore WordPressVIPMinimum.Performance.WPQueryParams.PostNotIn_exclude -- at most the hold's own bound.
				'fields'      => 'ids',
				'number'      => self::FLAGGED_MAX,
				'orderby'     => 'ID',
				'count_total' => true,
			)
		);

		$ids   = array_map( 'intval', (array) $query->get_results() );
		$total = max( (int) $query->get_total(), count( $ids ) );

		// One read for the page's accounts and their meta together, rather
		// than one for every account in it.
		if ( array() !== $ids ) {
			cache_users( $ids );
		}

		$privileged = 0;

		foreach ( $ids as $id ) {
			$user = get_userdata( $id );

			if ( $user instanceof \WP_User && $this->is_privileged( (array) $user->roles, $user ) ) {
				++$privileged;
			}
		}

		self::$flagged[ $site ] = array(
			'total'      => $total,
			'privileged' => $privileged,
			'complete'   => count( $ids ) >= $total,
		);

		return self::$flagged[ $site ];
	}

	/**
	 * Drop what `flagged()` answered, so the next call reads again.
	 */
	public static function forget_flagged(): void {
		self::$flagged = array();
	}

	/**
	 * The flag itself changed hands, by whatever wrote it.
	 *
	 * @param mixed $meta_id
	 * @param mixed $user_id
	 * @param mixed $meta_key
	 */
	public static function forget_flagged_on_meta( $meta_id, $user_id, $meta_key = '' ): void {
		if ( is_string( $meta_key ) && str_starts_with( $meta_key, self::WEAK_META ) ) {
			self::forget_flagged();
		}
	}

