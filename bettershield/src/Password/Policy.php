<?php
/**
 * Password policy: a minimum standard for new passwords, and nothing at all
 * for existing ones.
 *
 * The line this feature must never cross is retroactivity. Enforcement runs
 * at the three moments someone is choosing a password — a reset, a profile
 * update, an admin creating an account — where a refusal costs one more
 * attempt at a form they are already on. It never runs at sign-in: a person
 * whose password predates the policy signs in exactly as before, and what
 * they meet is a finding and a calm prompt, not a locked door.
 *
 * Two whole surfaces are exempt by architecture rather than by option.
 * Application passwords are generated by WordPress, never chosen, so a
 * strength rule has nothing to say about them. Programmatic creation —
 * wp_insert_user() from a plugin, WP-CLI, an import — bypasses the form
 * validation hooks entirely, which is correct: a migration that suddenly
 * fails on password grounds would be this plugin breaking someone's site.
 * Both exemptions are stated on the Settings screen rather than discovered.
 *
 * Neither exemption covers a form a person types into. A store's account and
 * reset pages are such forms, they are where a shop's customers change their
 * passwords, and they are hooked here alongside the ones WordPress renders —
 * so "programmatic creation is exempt" is never read as covering them.
 *
 * One such form is left alone, and said so on the same screen: the password a
 * customer sets while placing an order, or on the order confirmation page
 * once it is placed. Both are the checkout path, where nothing from this
 * plugin runs, and neither hands the password to a hook that could refuse it.
 * The sign-in observer meets that password the first time it is used, the
 * way it meets one from before the policy.
 *
 * The rules themselves are deterministic and each names what it matched, so
 * a refusal can say what is wrong and what would pass — never a bare "too
 * weak". A guessing-resistance estimate in the style of zxcvbn is
 * deliberately not attempted server-side: an opaque score cannot explain a
 * refusal, and core already ships the real thing client-side as guidance.
 *
 * @package BetterShield
 */

declare( strict_types=1 );

namespace BetterShield\Password;

use BetterShield\Events\Writer;
use BetterShield\Recovery\SafeMode;
use BetterShield\Undo\SettingsLedger;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

final class Policy {

	public const OPTION = 'bettershield_password_policy';

	/**
	 * Flag on a user whose sign-in password fell below the policy. The flag
	 * is the only thing ever stored — never the password, never a score.
	 */
	public const WEAK_META = 'bettershield_password_below_policy';

	/**
	 * Roles held to the privileged bar. Everyone else gets the default bar.
	 */
	private const PRIVILEGED_ROLES = array( 'administrator', 'editor' );

	/**
	 * The capabilities that make an account privileged wherever this plugin
	 * asks — one definition, so the password bar, the event severities and
	 * the session rules cannot drift apart.
	 */
	private const PRIVILEGED_CAPS = array( 'manage_options', 'edit_users', 'promote_users' );

	/**
	 * How many flagged accounts one pass reads.
	 *
	 * A bound on the work, not on the answer: the total is counted by the
	 * database whatever the bound, and `flagged()` says whether the accounts
	 * it read for the privileged count were all of them.
	 */
	public const FLAGGED_MAX = 200;

	private static ?Policy $instance = null;

	/**
	 * What `flagged()` last answered in this request, by site: a network
	 * counts the members of the site being asked, so one answer does not
	 * serve another site.
	 *
	 * @var array<int, array{total: int, privileged: int, complete: bool}>
	 */
	private static array $flagged = array();

	public static function instance(): Policy {
		if ( null === self::$instance ) {
			self::$instance = new self();
		}

		return self::$instance;
	}

	private function __construct() {}

	/**
	 * What this plugin recommends, before anybody has chosen anything. See
	 * `Login\Protection::defaults()` for why these are held apart.
	 *
	 * @return array{enabled: bool, min_length: int, min_length_privileged: int, min_length_single_factor: int, single_factor_everyone: bool}
	 */
	public function defaults(): array {
		return array(
			'enabled'               => true,
			'min_length'            => 8,
			// Longer for the accounts that can change the site, which is the
			// whole reason there are two numbers rather than one.
			'min_length_privileged' => 12,
			// For an account a password alone opens: no second factor and no
			// verified passkey (#1854). NIST SP 800-63B-4 asks 15 there.
			'min_length_single_factor' => 15,
			// Held to that bar: admins and editors only, unless the owner
			// widens it. Store customers and members rarely have a second
			// factor, and an update must not raise every one of their bars.
			'single_factor_everyone' => false,
		);
	}

	/**
	 * @return array{enabled: bool, min_length: int, min_length_privileged: int, min_length_single_factor: int, single_factor_everyone: bool}
	 */
	public function settings(): array {
		$stored   = get_option( self::OPTION, array() );
		$stored   = is_array( $stored ) ? $stored : array();
		$defaults = $this->defaults();

		return array(
			'enabled'               => (bool) ( $stored['enabled'] ?? $defaults['enabled'] ),
			'min_length'            => max( 6, (int) ( $stored['min_length'] ?? $defaults['min_length'] ) ),
			'min_length_privileged' => max( 6, (int) ( $stored['min_length_privileged'] ?? $defaults['min_length_privileged'] ) ),
			'min_length_single_factor' => max( 6, (int) ( $stored['min_length_single_factor'] ?? $defaults['min_length_single_factor'] ) ),
			'single_factor_everyone' => (bool) ( $stored['single_factor_everyone'] ?? $defaults['single_factor_everyone'] ),
		);
	}

	/**
	 * Whether saving this input would lower the bar: the policy switched off,
	 * or a shorter minimum for either kind of account. Input the save would
	 * refuse lowers nothing, since nothing is written.
	 *
	 * @param array<string, mixed> $input
	 */
	public function weakens( array $input ): bool {
		$next = $this->validate( $input );

		if ( is_wp_error( $next ) ) {
			return false;
		}

		$current = $this->settings();

		return ( $current['enabled'] && ! $next['enabled'] )
			|| $next['min_length'] < $current['min_length']
			|| $next['min_length_privileged'] < $current['min_length_privileged']
			|| $next['min_length_single_factor'] < $current['min_length_single_factor']
			|| ( $current['single_factor_everyone'] && ! $next['single_factor_everyone'] );
	}

	/**
	 * Update the policy. Loosening it is as security-relevant as tightening
	 * it, so both directions land in the activity log with the new numbers —
	 * lengths are not secrets, and "who lowered the bar, and when" is a
	 * question the log exists to answer.
	 *
	 * @param array<string, mixed> $input
	 * @return array{enabled: bool, min_length: int, min_length_privileged: int, min_length_single_factor: int, single_factor_everyone: bool}|\WP_Error
	 */
	public function update_settings( array $input ) {
		$next = $this->validate( $input );

		if ( is_wp_error( $next ) ) {
			return $next;
		}

		// False is the one answer that has to stop the save: there was a prior
		// policy and it could not be written down, so proceeding would move the
		// bar with nothing to put it back. Null is the ordinary "there is
		// nothing here to record" and carries on.
		if ( false === SettingsLedger::record( 'password_policy', $this->settings(), $next ) ) {
			return new \WP_Error(
				'bettershield_ledger_failed',
				__( 'Nothing was changed: the undo record could not be saved.', 'bettershield' ),
				array( 'status' => 500 )
			);
		}

		update_option( self::OPTION, $next, false );

		Writer::instance()->record(
			'password_policy_updated',
			Writer::SEVERITY_INFO,
			array(
				'object_type' => 'setting',
				'object_id'   => self::OPTION,
				'context'     => $next,
			)
		);

		return $next;
	}

	/**
	 * The policy an input would become, or the refusal it would meet — with
	 * nothing saved. A settings import dry-runs through this so the plan it
	 * shows names the same refusal the apply would produce.
	 *
	 * @param array<string, mixed> $input
	 * @return array{enabled: bool, min_length: int, min_length_privileged: int, min_length_single_factor: int, single_factor_everyone: bool}|\WP_Error
	 */
	public function validate( array $input ) {
		// A key left out keeps its current value: a body that only raises the
		// minimum must not silently reset the privileged bar or re-enable a
		// policy the owner turned off.
		$current = $this->settings();

		$next = array(
			'enabled'               => isset( $input['enabled'] ) ? rest_sanitize_boolean( $input['enabled'] ) : $current['enabled'],
			'min_length'            => isset( $input['min_length'] ) ? (int) $input['min_length'] : $current['min_length'],
			'min_length_privileged' => isset( $input['min_length_privileged'] ) ? (int) $input['min_length_privileged'] : $current['min_length_privileged'],
			'min_length_single_factor' => isset( $input['min_length_single_factor'] ) ? (int) $input['min_length_single_factor'] : $current['min_length_single_factor'],
			'single_factor_everyone' => isset( $input['single_factor_everyone'] ) ? rest_sanitize_boolean( $input['single_factor_everyone'] ) : $current['single_factor_everyone'],
		);

		foreach ( array( 'min_length', 'min_length_privileged', 'min_length_single_factor' ) as $key ) {
			if ( $next[ $key ] < 6 || $next[ $key ] > 64 ) {
				return new \WP_Error(
					'bettershield_bad_length',
					__( 'Minimum lengths need to be between 6 and 64 characters.', 'bettershield' ),
					array( 'status' => 400 )
				);
			}
		}

		if ( $next['min_length_privileged'] < $next['min_length'] ) {
			return new \WP_Error(
				'bettershield_bars_inverted',
				__( 'The minimum for admins and editors cannot be lower than for everyone else.', 'bettershield' ),
				array( 'status' => 400 )
			);
		}

		return $next;
	}

	/**
	 * Whether the policy is refusing anything right now: on, and not paused.
	 * Safe mode pauses every protection this plugin has, and an owner using
	 * the recovery link to reset a password must not meet a refusal from the
	 * plugin they are recovering from — the policy cannot lock anyone out,
	 * but "everything is paused" has to mean everything.
	 */
	private function enforcing(): bool {
		return $this->settings()['enabled'] && ! SafeMode::is_active();
	}

	/* ---- hooks ---------------------------------------------------------- */

	public function register(): void {
		// Enforcement: the two hooks every core path for CHOOSING a password
		// funnels through. Resets (which is also how core registration sets
		// the first password) and profile edits (which is also how an admin
		// types a password into a new-user form).
		add_action( 'validate_password_reset', array( $this, 'check_reset' ), 10, 2 );
		add_action( 'user_profile_update_errors', array( $this, 'check_profile' ), 10, 3 );

		// A store moves both of those forms to its own account pages, which is
		// where the sites with the most accounts on them do their password
		// changing. Its reset form fires the same core action as wp-login's,
		// under its own field name, which `check_reset()` now also reads; its
		// account form fires only this. Named rather than detected, because
		// the hook simply never fires on a site with no store — listing it
		// costs such a site nothing, and detecting would mean asking a
		// question whose answer changes mid-request.
		add_action( 'woocommerce_save_account_details_errors', array( $this, 'check_store_account' ), 10, 2 );

		// And the form where a shop's passwords are actually first chosen.
		// The store's sign-up carries the password in the request rather than
		// in a user object, and the filter the rest of this plugin uses on
		// that form — woocommerce_registration_errors — does not carry it at
		// all. This one does, so a store that lets customers pick their own
		// password holds them to the policy at the moment they pick it,
		// rather than only when they change it later.
		add_filter( 'woocommerce_process_registration_errors', array( $this, 'check_store_registration' ), 10, 4 );

		// The third path, and the one the two above miss entirely: core's own
		// REST users route. Neither hook above fires for it, so a policy that
		// looked enforced everywhere could be stepped around by any client
		// authenticating the way the block editor does — including creating a
		// new administrator with a three-character password.
		//
		// Not `rest_pre_insert_user`, which is the obvious choice and does not
		// work: core applies it inside prepare_item_for_database() and then
		// never checks whether what came back is an error, so a refusal there
		// is discarded and the write proceeds.
		//
		// Not `rest_request_before_callbacks` either, which runs *ahead* of
		// the route's own permission callback: a refusal there answers a
		// caller the route has not yet agreed to talk to, and each distinct
		// refusal reason is an answer — which side of the privileged length
		// bar an account sits on, and whether a guessed string is that
		// account's own login or email. `rest_dispatch_request` runs after the
		// permission callback, and core honors a WP_Error returned from it in
		// exactly the same way.
		add_filter( 'rest_dispatch_request', array( $this, 'check_rest' ), 10, 4 );

		// Observation, never enforcement: on a successful sign-in, note
		// whether the (correct) password meets the policy, so an old weak
		// password becomes a finding instead of staying invisible.
		add_filter( 'authenticate', array( $this, 'observe_login' ), 30, 3 );

		// The flag clears the moment a password changes: enforcement already
		// guaranteed the new one passes.
		add_action( 'after_password_reset', array( $this, 'clear_flag' ) );
		add_action( 'profile_update', array( $this, 'clear_flag_on_password_change' ), 10, 2 );

		// The count of flagged accounts is read once per request, so a flag
		// written or cleared by anything — this class, a profile save, an
		// import — drops it, or an audit later in the same request reads a
		// number that was true a moment ago.
		add_action( 'added_user_meta', array( self::class, 'forget_flagged_on_meta' ), 10, 3 );
		add_action( 'updated_user_meta', array( self::class, 'forget_flagged_on_meta' ), 10, 3 );
		add_action( 'deleted_user_meta', array( self::class, 'forget_flagged_on_meta' ), 10, 3 );

		// The prompt: a calm nudge on the affected user's own profile page,
		// and on a store's My Account, where its customers change theirs.
		add_action( 'admin_notices', array( $this, 'maybe_prompt' ) );
		add_action( 'woocommerce_account_content', array( $this, 'maybe_prompt_on_store' ), 5 );
	}

	/* ---- evaluation ------------------------------------------------------ */

	/**
	 * The bar for a set of roles.
	 *
	 * @param string[] $roles
	 */
	public function required_length( array $roles, ?\WP_User $user = null, ?int $length = null ): int {
		$settings = $this->settings();
		$base     = $this->role_length( $roles, $user );
		$single   = $settings['min_length_single_factor'];

		/*
		 * An existing account a password alone opens is held to the longer of
		 * its role's bar and the single-factor one (#1854). An account being
		 * created has no second factor yet by definition, so it keeps its
		 * role's bar and is asked again at its first sign-in if short.
		 *
		 * Whether it has one is asked only when the answer could change the
		 * outcome: a password already long enough for either bar costs the
		 * sign-in no read of the factor tables.
		 */
		if ( null === $user || $single <= $base || ( null !== $length && $length >= $single ) ) {
			return $base;
		}

		// Privileged accounts only, unless the owner widened it to everyone.
		if ( ! $settings['single_factor_everyone'] && ! $this->is_privileged( $roles, $user ) ) {
			return $base;
		}

		return $this->password_alone( $user ) ? $single : $base;
	}

	/**
	 * The bar a role sets, before the single-factor one is weighed.
	 *
	 * @param string[] $roles
	 */
	private function role_length( array $roles, ?\WP_User $user ): int {
		$settings = $this->settings();

		return $this->is_privileged( $roles, $user ) ? $settings['min_length_privileged'] : $settings['min_length'];
	}

	/**
	 * Whether a password is the only way into this account: no second factor
	 * and no verified passkey.
	 */
	public function password_alone( \WP_User $user ): bool {
		return $user->ID > 0
			&& ! \BetterShield\TwoFactor\Manager::instance()->enabled( (int) $user->ID )
			&& 0 === \BetterShield\Passkeys\Store::count_verified_for_user( (int) $user->ID );
	}

	/**
	 * Whether an account is held to the higher bar.
	 *
	 * Matching role slugs alone missed the two accounts that most needed the
	 * higher bar: a multisite super admin, who is often not an explicit
	 * `administrator` member of a given subsite, and any custom role somebody
	 * built with `manage_options`. Both could set a password below the minimum
	 * this setting exists to raise for them. The rest of this plugin is
	 * already super-admin aware; this was the gap.
	 *
	 * The slugs stay, so a site that renamed nothing behaves exactly as before.
	 *
	 * @param string[] $roles
	 */
	public function is_privileged( array $roles, ?\WP_User $user = null ): bool {
		if ( array() !== array_intersect( $roles, self::PRIVILEGED_ROLES ) ) {
			return true;
		}

		if ( null === $user ) {
			/*
			 * Creation: there is no account yet to ask user_can() of, but the
			 * roles it will hold are named — and a custom role carrying a
			 * high-privilege capability is exactly what the privileged bar is
			 * for. Falling through to the slug list alone would let a new
			 * account in a bespoke manage_options role be created with the
			 * default bar — the counterpart of the by-capability rule
			 * existing accounts already get below.
			 */
			return $this->roles_are_privileged( $roles );
		}

		if ( is_multisite() && is_super_admin( $user->ID ) ) {
			return true;
		}

		foreach ( self::PRIVILEGED_CAPS as $capability ) {
			if ( user_can( $user, $capability ) ) {
				return true;
			}
		}

		return false;
	}

	/**
	 * Whether an account is privileged, from whatever the caller holds — an
	 * ID, a WP_User, or nothing that resolves. The severity-escalation and
	 * session-reset call sites all ask this one question.
	 *
	 * @param int|\WP_User|mixed $user
	 */
	public function user_is_privileged( $user ): bool {
		if ( is_numeric( $user ) ) {
			$user = get_user_by( 'id', (int) $user );
		}

		return $user instanceof \WP_User && $this->is_privileged( (array) $user->roles, $user );
	}

	/**
	 * Whether a set of role slugs carries a privileged capability — the
	 * answer available when there is no account yet, or only slugs.
	 *
	 * @param string[] $roles
	 */
	public function roles_are_privileged( array $roles ): bool {
		foreach ( $roles as $slug ) {
			$role = get_role( (string) $slug );

			if ( null === $role ) {
				continue;
			}

			foreach ( self::PRIVILEGED_CAPS as $capability ) {
				if ( $role->has_cap( $capability ) ) {
					return true;
				}
			}
		}

		return false;
	}

	/**
	 * The accounts a user query finds that are held to the higher bar, by ID,
	 * asked of the database rather than of each account: the roles and the
	 * capabilities is_privileged() asks about, and on a network its super
	 * admins. For ordering a long list without loading it; a capability that
	 * only a filter grants at runtime is not in the database to be found.
	 *
	 * @param array<string, mixed> $query WP_User_Query arguments that narrow the accounts asked about.
	 * @return int[]
	 */
	public function privileged_ids( array $query = array() ): array {
		$ids = array();

		foreach ( array( array( 'role__in' => self::PRIVILEGED_ROLES ), array( 'capability__in' => self::PRIVILEGED_CAPS ) ) as $by ) {
			$ids = array_merge( $ids, get_users( array( 'fields' => 'ID' ) + $by + $query ) );
		}

		if ( is_multisite() ) {
			foreach ( get_super_admins() as $login ) {
				$super = get_user_by( 'login', (string) $login );

				if ( $super instanceof \WP_User ) {
					$ids[] = $super->ID;
				}
			}
		}

		return array_values( array_unique( array_map( 'intval', $ids ) ) );
	}

	/**
	 * The name the screens give the one role a password is checked for, or ''
	 * where there is not exactly one role this site knows.
	 *
	 * @param string[] $roles Role slugs.
	 */
	private static function role_name( array $roles ): string {
		$names = wp_roles()->role_names;
		$known = array_values( array_filter( array_unique( array_map( 'strval', $roles ) ), static fn( string $role ): bool => isset( $names[ $role ] ) ) );

		return 1 === count( $known ) ? translate_user_role( (string) $names[ $known[0] ] ) : '';
	}

	/**
	 * Evaluate a password against the policy for a user context. Null when it
	 * passes; otherwise an error whose message names what is wrong and what
	 * would satisfy the rule.
	 *
	 * @param string[] $roles   The roles the account holds or will hold.
	 * @param string[] $words   User-derived words: login, email, display name.
	 * @param \WP_User|null $user The account itself, where there is one: a
	 *                            super admin and a custom high-capability role
	 *                            are both held to the higher bar, and neither
	 *                            can be recognized from a role slug.
	 */
	public function evaluate( string $password, array $roles, array $words = array(), ?\WP_User $user = null ): ?\WP_Error {
		/*
		 * The password WordPress will store, not the one as it was sent. Core
		 * hashes it trimmed and trims it again at sign-in, while the REST
		 * routes and the store's forms hand it over as typed — so four
		 * characters with spaces around them were measured as twelve and
		 * stored as four.
		 */
		$password = trim( $password );
		$length   = $this->char_length( $password );
		$required = $this->required_length( $roles, $user, $length );

		/*
		 * Someone signed in setting another account's password, or a new
		 * one's: an administrator adding a subscriber was told the bar was
		 * 8 "for your role", which is the subscriber's, while their own is
		 * 12 (#2082). That case names the account's role instead.
		 */
		$for_another = is_user_logged_in() && ( ! $user instanceof \WP_User || (int) $user->ID !== get_current_user_id() );

		// The single-factor bar is the one that bites: said as that, since
		// "your role needs" would name a number the role does not ask.
		$alone = $required > $this->role_length( $roles, $user );

		if ( $length < $required ) {
			if ( $alone ) {
				$message = sprintf(
					/* translators: 1: number of characters entered, 2: number required. */
					_n(
						'This password is %1$d character. An account without a second factor or passkey needs at least %2$d. Try a few unrelated words.',
						'This password is %1$d characters. An account without a second factor or passkey needs at least %2$d. Try a few unrelated words.',
						$length,
						'bettershield'
					),
					$length,
					$required
				);
			} elseif ( ! $for_another ) {
				$message = sprintf(
					/* translators: 1: number of characters entered, 2: number required. */
					_n(
						'This password is %1$d character. Your role needs at least %2$d. Try a few unrelated words.',
						'This password is %1$d characters. Your role needs at least %2$d. Try a few unrelated words.',
						$length,
						'bettershield'
					),
					$length,
					$required
				);
			} elseif ( '' !== self::role_name( $roles ) ) {
				$message = sprintf(
					/* translators: 1: number of characters entered, 2: number required, 3: the role of the account whose password it is. */
					_n(
						'This password is %1$d character. The %3$s role needs at least %2$d. Try a few unrelated words.',
						'This password is %1$d characters. The %3$s role needs at least %2$d. Try a few unrelated words.',
						$length,
						'bettershield'
					),
					$length,
					$required,
					self::role_name( $roles )
				);
			} else {
				$message = sprintf(
					/* translators: 1: number of characters entered, 2: number required. */
					_n(
						'This password is %1$d character. That account’s role needs at least %2$d. Try a few unrelated words.',
						'This password is %1$d characters. That account’s role needs at least %2$d. Try a few unrelated words.',
						$length,
						'bettershield'
					),
					$length,
					$required
				);
			}

			return new \WP_Error( 'bettershield_password_short', $message );
		}

		$core = $this->core_word( $password );

		foreach ( $this->derived_words( $words ) as $word ) {
			if ( $core === $word || strtolower( $password ) === $word ) {
				return new \WP_Error(
					'bettershield_password_derived',
					$for_another
						? __( 'This password uses the account’s username, email or site name, which are easy to guess. Pick something unrelated.', 'bettershield' )
						: __( 'This password uses your username, email or site name, which are easy to guess. Pick something unrelated.', 'bettershield' ),
					array()
				);
			}
		}

		if ( in_array( $core, CommonWords::LIST, true ) ) {
			return new \WP_Error(
				'bettershield_password_common',
				__( 'This password uses a very commonly guessed word. Try a password manager’s suggestion or a few unrelated words.', 'bettershield' ),
				array()
			);
		}

		if ( $this->is_single_run( $password ) ) {
			return new \WP_Error(
				'bettershield_password_pattern',
				__( 'This password is one repeated or sequential run of characters, which is easy to guess. Add unrelated words.', 'bettershield' ),
				array()
			);
		}

		return null;
	}

	/**
	 * The word a password is built from: lowercased, with the decorating
	 * digits and punctuation people append or prepend stripped. This is what
	 * turns "Password2026!" into "password" before the lists are consulted.
	 */
	private function core_word( string $password ): string {
		/*
		 * Both the lowercasing and the trim have to be told the string is
		 * UTF-8. Without the `/u` modifier the pattern runs byte-wise, every
		 * byte of a multi-byte character matches `\W`, and a password written
		 * entirely in a non-Latin script was stripped to the empty string —
		 * which then passed both checks by default. The length check still
		 * applied, but a site whose name or an account's display name is in
		 * Bengali, Arabic, Cyrillic or Japanese got no protection at all from a
		 * password built out of it.
		 */
		$word = $this->folded( $password );
		$word = function_exists( 'mb_strtolower' ) ? mb_strtolower( $word, 'UTF-8' ) : strtolower( $word );
		$word = (string) preg_replace( '/^[\d\W_]+|[\d\W_]+$/u', '', $word );

		return $word;
	}

	/**
	 * The same letters however they were typed. Full-width "ｐａｓｓｗｏｒｄ" is
	 * "password" to anybody guessing, so compatibility normalization runs
	 * before any list is read. intl is optional on cheap hosts; without it
	 * the full-width block, the case seen in practice, is folded by hand.
	 */
	private function folded( string $text ): string {
		if ( class_exists( 'Normalizer' ) ) {
			$normal = \Normalizer::normalize( $text, \Normalizer::FORM_KC );

			return is_string( $normal ) ? $normal : $text;
		}

		return (string) preg_replace_callback(
			'/[\x{FF01}-\x{FF5E}]/u',
			static function ( array $wide ): string {
				// Three UTF-8 bytes; the full-width form sits 0xFEE0 above its ASCII one.
				$point = ( ( ord( $wide[0][0] ) & 0x0F ) << 12 ) | ( ( ord( $wide[0][1] ) & 0x3F ) << 6 ) | ( ord( $wide[0][2] ) & 0x3F );

				return chr( $point - 0xFEE0 );
			},
			$text
		);
	}

	/**
	 * Words an attacker derives from the account and the site itself.
	 *
	 * @param string[] $extra
	 * @return string[]
	 */
	private function derived_words( array $extra ): array {
		$words = $extra;

		$host = (string) wp_parse_url( home_url(), PHP_URL_HOST );
		if ( '' !== $host ) {
			$words[] = $host;
			// The name is the label after "www.", not "www" itself.
			$parts   = explode( '.', (string) preg_replace( '/^www\./i', '', $host ) );
			$words[] = (string) $parts[0];
		}

		// "Acme Shop" is typed as "AcmeShop" in a password, so the name is
		// compared without its spaces too.
		$name    = (string) get_option( 'blogname' );
		$words[] = $name;
		$words[] = (string) preg_replace( '/\s+/u', '', $name );

		$out = array();
		foreach ( $words as $word ) {
			// mb-aware for the same reason `core_word()` is: a site name or a
			// display name in a non-Latin script has to be comparable with the
			// password it might have been built from.
			$word = trim( (string) $word );
			$word = function_exists( 'mb_strtolower' ) ? mb_strtolower( $word, 'UTF-8' ) : strtolower( $word );

			// Emails contribute their local part as well as the whole.
			if ( str_contains( $word, '@' ) ) {
				$out[] = (string) strstr( $word, '@', true );
			}

			if ( '' !== $word ) {
				$out[] = $word;
			}
		}

		return array_values( array_unique( array_filter( $out ) ) );
	}

	/**
	 * Whether the whole password is one repeated character or one straight
	 * ascending or descending run ("aaaaaaaa", "12345678", "hgfedcba").
	 */
	private function is_single_run( string $password ): bool {
		$length = strlen( $password );

		// One character repeated is a pattern in any script, and as an emoji:
		// "аааааааааааа" and "éééééééé" are no better than "aaaaaaaa". The
		// character carries the marks, variation selector or skin tone that
		// follow it, so one typed as several code points still counts as one.
		// Not `\X`: older PCRE reads a whole run of emoji as one grapheme.
		if ( 1 === preg_match( '/^(.[\p{M}\x{FE00}-\x{FE0F}\x{1F3FB}-\x{1F3FF}]*)\1{3,}$/us', $password ) ) {
			return true;
		}

		if ( $length < 4 || $length !== $this->char_length( $password ) ) {
			return false; // Multibyte content is not a keyboard run.
		}

		$repeated  = true;
		$ascending = true;
		$descending = true;

		for ( $i = 1; $i < $length; $i++ ) {
			$step = ord( $password[ $i ] ) - ord( $password[ $i - 1 ] );

			if ( 0 !== $step ) {
				$repeated = false;
			}
			// The digit row wraps: "…890" is typed as a run and counts as one.
			if ( 1 !== $step && ! ( '9' === $password[ $i - 1 ] && '0' === $password[ $i ] ) ) {
				$ascending = false;
			}
			if ( -1 !== $step && ! ( '0' === $password[ $i - 1 ] && '9' === $password[ $i ] ) ) {
				$descending = false;
			}
		}

		return $repeated || $ascending || $descending;
	}

	/**
	 * Character count, not byte count: a passphrase in any script measures
	 * by what its owner typed. mbstring is optional on cheap hosts, so the
	 * count comes from the regex engine instead.
	 */
	private function char_length( string $password ): int {
		$count = preg_match_all( '/./us', $password );

		return false === $count ? strlen( $password ) : $count;
	}

